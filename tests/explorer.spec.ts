import { test, expect } from '@playwright/test';
import path from 'node:path';

const artifacts = process.env.ARTIFACT_DIR ?? 'test-results';

test('dashboard controls stay synchronized across search, playback, and protocol changes', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1912, height: 987 });
  await page.goto('http://127.0.0.1:5173');
  await expect(page.getByRole('heading', { name: 'HTTP', exact: true })).toBeVisible();
  await expect(page.locator('.packet-table tbody tr')).toHaveCount(7);
  await page.getByRole('button', { name: 'STEP', exact: true }).click();
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '0');
  await page.getByRole('button', { name: /Inspect packet 2:/ }).click();
  await expect(page.getByRole('heading', { name: 'PACKET INSPECTOR' })).toBeVisible();
  await expect(page.locator('.inspector .packet-info')).toContainText('query response');
  await page.getByText('Hexadecimal / ASCII', { exact: true }).click();
  await expect(page.locator('.hex-dump')).toBeVisible();
  await page.getByRole('tab', { name: 'SEQUENCE' }).click();
  await expect(page.getByRole('button', { name: /Inspect packet 3:/ })).toHaveCount(2);
  await page.locator('.sequence-packet').nth(2).click();
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '2');
  await expect(page.locator('.inspector .packet-info')).toContainText('[SYN]');
  await page.getByRole('button', { name: 'RESET', exact: true }).click();
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await page.getByLabel('Playback speed').selectOption('4');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await expect(page.getByRole('button', { name: 'PAUSE', exact: true })).toBeVisible();
  await expect(page.locator('.diagram-state')).toHaveText('FLOW COMPLETE', { timeout: 5000 });
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '6');
  await page.waitForTimeout(500);
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '6');

  await page.keyboard.press('Control+k');
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('textbox', { name: 'Search protocols' }).fill('wireguard');
  await expect(page.locator('.search-results > button')).toHaveCount(1);
  await page.getByRole('textbox', { name: 'Search protocols' }).press('Enter');
  await expect(page.getByRole('heading', { name: 'WireGuard', exact: true })).toBeVisible();
  await expect(page.locator('.packet-table tbody tr')).toHaveCount(4);
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await page.getByRole('button', { name: 'CORE 11', exact: true }).click();
  await expect(page.locator('.protocol-entry')).toHaveCount(11);
  await page.getByRole('button', { name: 'ALL 39', exact: true }).click();
  await page.getByRole('button', { name: /HTTP Hypertext/ }).click();
  await page.getByRole('button', { name: 'Toggle diagram only' }).click();
  await expect(page.locator('.overview-panel')).toHaveCount(0);
  await expect(page.locator('.protocol-panel')).toHaveCount(0);
  await page.getByRole('button', { name: 'Toggle diagram only' }).click();
  await page.getByRole('button', { name: 'Toggle protocol list' }).click();
  await expect(page.locator('.protocol-panel')).toHaveCount(0);
  await page.getByRole('button', { name: 'Toggle protocol list' }).click();
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await page.getByRole('button', { name: 'Keyboard shortcuts', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('Play / pause');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('tab', { name: 'NETWORK' }).click();
  await page.getByRole('button', { name: 'RESET', exact: true }).click();
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 1912);
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(200);
  await page.screenshot({ path: path.join(artifacts, 'protocol-explorer-desktop.png'), fullPage: true });

  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Search protocols' })).toBeVisible();
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 390);
  await page.screenshot({ path: path.join(artifacts, 'protocol-explorer-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'STEP', exact: true }).click();
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '0');
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await page.waitForTimeout(200);
  await page.screenshot({ path: path.join(artifacts, 'protocol-explorer-light.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('every lesson renders its own flow and switching during playback clears the old timer', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('http://127.0.0.1:5173');
  const protocolNames = await page.locator('.protocol-button strong').allTextContents();
  for (const name of protocolNames) {
    await page.keyboard.press('Control+k');
    await page.getByRole('textbox', { name: 'Search protocols' }).fill(name);
    await page.locator('.search-results button').filter({ has: page.getByText(name, { exact: true }) }).click();
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
    await expect(page.locator('.packet-table tbody tr').first()).toBeVisible();
    await page.getByRole('tab', { name: 'SEQUENCE' }).click();
    const count = await page.locator('.packet-table tbody tr').count();
    await expect(page.locator('.sequence-packet')).toHaveCount(count);
    await page.getByRole('tab', { name: 'NETWORK' }).click();
  }
  await page.getByLabel('Playback speed').selectOption('4');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.keyboard.press('Control+k');
  const input = page.getByRole('textbox', { name: 'Search protocols' });
  await input.fill('DHCP');
  await input.press('Enter');
  await page.waitForTimeout(700);
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'PLAY', exact: true })).toBeVisible();
  await page.keyboard.press('Control+k');
  await input.fill('no-such-protocol');
  await expect(page.getByRole('heading', { name: 'No matching protocols' })).toBeVisible();
  await input.fill('r');
  await input.press('Space');
  await expect(input).toHaveValue('r ');
  await expect(page.getByRole('button', { name: 'PLAY', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.locator('.section-heading').first().click();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '0');
  await page.keyboard.press('r');
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.waitForTimeout(350);
  await expect(page.locator('animateMotion')).toHaveCount(0);
  expect(errors).toEqual([]);
});
