test('every lesson renders its own flow and switching during playback clears the old timer', async ({ page }) => {
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(site);
  const protocolNames = await page.locator('.protocol-button strong').allTextContents();
  for (const name of protocolNames) {
    await page.keyboard.press('Control+k');
    await page.getByRole('textbox', { name: 'Search protocols' }).fill(name);
    await page.locator('.search-results button').filter({ has: page.getByText(name, { exact: true }) }).click();
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
    await expect(page.locator('.packet-table tbody tr').first()).toBeVisible();
    await page.getByRole('tab', { name: 'SEQUENCE' }).click();
    const count = await page.locator('.packet-table tbody tr').count();
    await expect(page.locator('.sequence-packet')).toHaveCount(count);
    await page.getByRole('tab', { name: 'NETWORK' }).click();
  }
  await page.getByLabel('Playback speed').selectOption('4');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.keyboard.press('Control+k');
  const input = page.getByRole('textbox', { name: 'Search protocols' });
  await input.fill('DHCP');
  await input.press('Enter');
  await page.waitForTimeout(700);
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'PLAY', exact: true })).toBeVisible();
  await page.keyboard.press('Control+k');
  await input.fill('no-such-protocol');
  await expect(page.getByRole('heading', { name: 'No matching protocols' })).toBeVisible();
  await input.fill('r');
  await input.press('Space');
  await expect(input).toHaveValue('r ');
  await expect(page.getByRole('button', { name: 'PLAY', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.locator('.section-heading').first().click();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '0');
  await page.keyboard.press('r');
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.waitForTimeout(350);
  await expect(page.locator('animateMotion')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('packet motion follows playback continuously through pause, speed changes, replies and final arrival', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') });
  await page.goto(site);
  await page.clock.pauseAt(new Date('2026-01-01T01:00:00Z'));
  await page.getByLabel('Playback speed').selectOption('0.5');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('data-route', 'client,router,dns');
  const progress = () => page.locator('.network-svg').getAttribute('data-progress').then(Number);
  await page.clock.runFor(150);
  const start = await page.locator('.network-packet-marker').getAttribute('transform');
  const firstProgress = await progress();
  await page.clock.runFor(250);
  expect(await page.locator('.network-packet-marker').getAttribute('transform')).not.toBe(start);
  const slowProgress = await progress();
  expect(slowProgress).toBeGreaterThan(firstProgress);
  await page.getByRole('button', { name: 'PAUSE', exact: true }).click();
  const paused = await page.locator('.network-packet-marker').getAttribute('transform');
  const pausedProgress = await progress();
  await page.clock.runFor(250);
  expect(await page.locator('.network-packet-marker').getAttribute('transform')).toBe(paused);
  expect(await progress()).toBe(pausedProgress);
  await page.getByLabel('Playback speed').selectOption('2');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.clock.runFor(200);
  expect(await progress()).toBeGreaterThan(pausedProgress + .2);
  await page.getByRole('button', { name: 'PAUSE', exact: true }).click();
  const beforeViewSwitch = await progress();
  await page.getByRole('tab', { name: 'SEQUENCE' }).click();
  await expect(page.locator('.sequence-svg')).toHaveAttribute('data-progress', String(beforeViewSwitch));
  await expect(page.locator('.sequence-packet-marker')).toHaveAttribute('data-source', 'client');
  const beforeSequence = Number(await page.locator('.sequence-packet-marker').getAttribute('cx'));
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.clock.runFor(100);
  expect(Number(await page.locator('.sequence-packet-marker').getAttribute('cx'))).toBeGreaterThan(beforeSequence);
  await page.getByRole('button', { name: 'PAUSE', exact: true }).click();
  await page.getByRole('button', { name: 'RESET', exact: true }).click();
  await expect(page.locator('.sequence-packet-marker')).toHaveCount(0);
  await page.getByRole('tab', { name: 'NETWORK' }).click();
  await page.getByRole('button', { name: /Inspect packet 1:/ }).click();
  await page.getByLabel('Playback speed').selectOption('0.5');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('data-route', 'dns,router,client');
  await page.getByRole('button', { name: 'PAUSE', exact: true }).click();
  await page.getByRole('button', { name: /Inspect packet 6:/ }).click();
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('data-route', 'server,internet,router,client');
  await page.clock.runFor(200);
  await expect(page.getByRole('button', { name: 'PAUSE', exact: true })).toBeVisible();
  expect(await progress()).toBeLessThan(1);
  await page.getByLabel('Playback speed').selectOption('4');
  await page.clock.runFor(400);
  await expect(page.locator('.diagram-state')).toHaveText('FLOW COMPLETE');
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('transform', 'translate(230 385)');
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '6');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '0');
  await page.getByRole('button', { name: 'RESET', exact: true }).click();
  await expect(page.locator('.network-packet-marker')).toHaveCount(0);

  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByLabel('Playback speed').selectOption('0.5');
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await expect(page.locator('.diagram-state')).toContainText('REDUCED MOTION');
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('transform', 'translate(555 125)');
  await page.clock.runFor(200);
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('transform', 'translate(555 125)');
  await page.keyboard.press('Control+k');
  await page.getByRole('textbox', { name: 'Search protocols' }).fill('Wi-Fi');
  await page.getByRole('textbox', { name: 'Search protocols' }).press('Enter');
  await expect(page.locator('.network-packet-marker')).toHaveCount(0);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('button', { name: 'PLAY', exact: true }).click();
  await page.clock.runFor(300);
  await expect(page.locator('.network-packet-marker')).toHaveAttribute('data-route', 'client,server');
  await expect(page.locator('.network-svg')).toHaveAttribute('data-packet', '0');
});
