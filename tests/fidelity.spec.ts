import { test, expect } from '@playwright/test';
import path from 'node:path';

const site = process.env.PREVIEW_URL ?? 'http://127.0.0.1:5173';
const artifacts = process.env.ARTIFACT_DIR ?? 'test-results';

test('lesson stages are searchable, local actions do not fabricate packets, and scoped playback stops at the stage boundary', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') });
  await page.goto(site);
  await page.clock.pauseAt(new Date('2026-01-01T01:00:00Z'));
  await page.locator('.section-heading').first().click();
  await page.keyboard.press('5');
  await expect(page.locator('.step-narration h2')).toHaveText('Page rendering');
  await expect(page.locator('.local-step-note')).toContainText('no new packet');
  await expect(page.locator('.packet-table tbody tr')).toHaveCount(7);
  await page.keyboard.press('Escape');
  await expect(page.locator('.current-packet')).toHaveCount(0);
  await page.keyboard.press('/');
  await page.getByRole('textbox', { name: 'Search protocols' }).fill('page rendering');
  await expect(page.locator('.search-results > button')).toHaveCount(1);
  await expect(page.locator('.search-results')).toContainText('HTTP · Lesson stage 5');
  await page.getByRole('textbox', { name: 'Search protocols' }).press('Enter');
  await expect(page.locator('.step-narration h2')).toHaveText('Page rendering');
  await page.keyboard.press('Escape');
  await page.locator('.section-heading').first().click();
  await page.keyboard.press('2');
  await page.clock.runFor(2500);
  await expect(page.locator('.diagram-state')).toHaveText('STEP COMPLETE');
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '1');
  await expect(page.locator('.step-narration h2')).toHaveText('DNS resolution');
  await page.clock.runFor(1500);
  await expect(page.locator('.current-packet')).toHaveAttribute('data-packet', '1');
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.step-narration h2')).toHaveText('TCP connection');
  await page.keyboard.press('v');
  await expect(page.getByRole('tab', { name: 'SEQUENCE' })).toHaveAttribute('aria-selected', 'true');
  await page.keyboard.press('t');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.keyboard.press(']');
  await expect(page.getByLabel('Playback speed')).toHaveValue('2');
});

test('packet inspection decodes DNS as UDP, maps fields to bytes, and works with keyboard navigation in diagram-only mode', async ({ page }) => {
  await page.goto(site);
  await page.getByRole('button', { name: /Inspect packet 1:/ }).click();
  await expect(page.locator('.inspector .decode-fields')).toContainText('UDP');
  await page.getByRole('button', { name: /Transaction ID 0x4a2b/ }).click();
  await expect(page.locator('.byte-panel')).toHaveAttribute('open', '');
  await expect(page.locator('.hex-bytes .byte-highlight')).toHaveCount(2);
  await expect(page.locator('.hex-bytes [data-offset="42"]')).toHaveText('4a');
  await expect(page.locator('.hex-bytes [data-offset="43"]')).toHaveText('2b');
  await page.getByRole('button', { name: 'Close packet inspector' }).click();
  await expect(page.getByRole('button', { name: /Inspect packet 1:/ })).toBeFocused();
  await page.getByRole('button', { name: 'Toggle diagram only' }).click();
  await page.getByRole('button', { name: /Inspect packet 3:/ }).click();
  await expect(page.locator('.floating-inspector')).toBeVisible();
  await expect(page.locator('.inspector .decode-fields')).toContainText('TCP');
  await expect(page.getByRole('button', { name: /TCP flags SYN/ })).toBeVisible();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('.inspector .packet-info')).toContainText('[SYN, ACK]');
  await page.keyboard.press('Escape');
  await expect(page.locator('.floating-inspector')).toHaveCount(0);
  await page.getByRole('button', { name: 'Toggle diagram only' }).click();
  await page.keyboard.press('Control+k');
  await page.getByRole('textbox', { name: 'Search protocols' }).fill('WPA3');
  await page.getByRole('textbox', { name: 'Search protocols' }).press('Enter');
  await page.locator('.packet-select').first().click();
  await expect(page.locator('.inspector')).toContainText('Wire bytes and transport fields are unavailable');
  await expect(page.locator('.byte-panel')).toHaveCount(0);
});

test('mobile prioritizes the diagram, keeps controls reachable and supports stage search and packet inspection', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(site);
  await expect(page.locator('.protocol-panel')).toHaveCount(0);
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 390);
  await expect(page.getByRole('button', { name: 'PLAY', exact: true })).toBeInViewport();
  await page.getByRole('button', { name: 'Toggle protocol list' }).click();
  await expect(page.getByRole('button', { name: /5Page rendering|5 Page rendering/ })).toBeVisible();
  await page.getByRole('button', { name: /5Page rendering|5 Page rendering/ }).click();
  await expect(page.locator('.protocol-panel')).toHaveCount(0);
  await expect(page.locator('.step-narration h2')).toHaveText('Page rendering');
  await page.getByRole('button', { name: 'RESET', exact: true }).click();
  await page.getByRole('button', { name: 'Search protocols' }).click();
  await page.getByRole('textbox', { name: 'Search protocols' }).fill('DNS');
  await page.locator('.search-results button').filter({ has: page.getByText('DNS', { exact: true }) }).click();
  await expect(page.locator('.packet-table tbody tr')).toHaveCount(4);
  await page.getByRole('button', { name: /Inspect packet 1:/ }).click();
  await expect(page.locator('.inspector')).toBeVisible();
  await expect(page.getByRole('button', { name: 'PLAY', exact: true })).toBeInViewport();
  await page.getByRole('button', { name: 'Close packet inspector' }).click();
  await page.screenshot({ path: path.join(artifacts, 'protocol-explorer-improved-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Switch to light mode' }).click();
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 390);
  expect(errors).toEqual([]);
});
