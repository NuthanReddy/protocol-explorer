export interface StepMechanism {
  name: string;
  walkthrough: [string, string, string];
  note?: string;
}

function mechanism(name: string, input: string, rule: string, result: string, note?: string): StepMechanism {
  return { name, walkthrough: [input, rule, result], ...(note ? { note } : {}) };
}

